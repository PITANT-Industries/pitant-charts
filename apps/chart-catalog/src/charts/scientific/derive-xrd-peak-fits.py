"""Derive bounded pseudo-Voigt fits from the catalog's measured DyNiC₂ scans.

From this directory, run uv run derive-xrd-peak-fits.py > xrd-peak-data.ts.
"""

import hashlib
import json
from pathlib import Path
import sys

import numpy as np
from scipy.optimize import least_squares


MEASUREMENTS = Path(__file__).parent / "waterfall" / "xrd-measurements.json"
MEASUREMENT_SHA256 = "85e6a32ea5d2384fae1c3b211cb7b1283113211105b224726228cdac7388f5d6"
WINDOWS = (
    ("peak-low", "Near 5.20°", (5.157, 5.247)),
    ("peak-middle", "Near 5.29°", (5.252, 5.322)),
    ("peak-high", "Near 5.36°", (5.324, 5.407)),
)
GAUSSIAN_FACTOR = 4 * np.log(2)
PARAMETERS = ("centerDeg", "fwhmDeg", "height", "background", "backgroundSlope", "lorentzFraction")


def load_measurements():
    raw = MEASUREMENTS.read_bytes()
    if hashlib.sha256(raw).hexdigest() != MEASUREMENT_SHA256:
        raise ValueError("Unexpected DyNiC₂ source grid.")
    source = json.loads(raw)
    angles = np.array(source["spectralBins"])
    temperatures = np.array(source["scanValues"])
    intensities = np.array(source["intensityRows"])
    if (
        angles.shape != (163,) or temperatures.shape != (16,) or intensities.shape != (16, 163)
        or not all(np.isfinite(array).all() for array in (angles, temperatures, intensities))
        or not ((np.diff(angles) > 0).all() and (np.diff(temperatures) > 0).all())
    ):
        raise ValueError("Expected 16 ordered temperatures and 163 aligned diffraction samples.")
    return angles, temperatures, intensities


def peak_fit(angle, intensity):
    if angle.size < 8:
        return None
    spacing = np.median(np.diff(angle))
    span = angle[-1] - angle[0]
    best_sample = np.argmax(intensity)
    baseline = np.median(np.r_[intensity[:3], intensity[-3:]])
    height = intensity[best_sample] - baseline
    if height <= 0:
        return None

    width = np.count_nonzero(intensity >= baseline + height / 2) * spacing
    bounds = ([angle[1], spacing, 0, 0, -np.inf, 0], [angle[-2], span, np.inf, np.inf, np.inf, 1])
    center = np.clip(angle[best_sample], angle[1], angle[-2])
    slope = (np.mean(intensity[-3:]) - np.mean(intensity[:3])) / span

    def residual(parameters):
        center_deg, fwhm_deg, height, background, slope, mix = parameters
        offset = angle - center_deg
        ratio = offset / fwhm_deg
        gaussian = np.exp(-GAUSSIAN_FACTOR * ratio ** 2)
        lorentzian = 1 / (1 + 4 * ratio ** 2)
        estimate = background + slope * offset + height * ((1 - mix) * gaussian + mix * lorentzian)
        return estimate - intensity

    def jacobian(parameters):
        center_deg, fwhm_deg, height, _, slope, mix = parameters
        offset = angle - center_deg
        ratio = offset / fwhm_deg
        gaussian = np.exp(-GAUSSIAN_FACTOR * ratio ** 2)
        lorentzian = 1 / (1 + 4 * ratio ** 2)
        profile = (1 - mix) * gaussian + mix * lorentzian
        derivative = -2 * ratio * ((1 - mix) * GAUSSIAN_FACTOR * gaussian + mix * 4 * lorentzian ** 2)
        return np.column_stack((
            -height * derivative / fwhm_deg - slope,
            -height * derivative * ratio / fwhm_deg,
            profile,
            np.ones_like(angle),
            offset,
            height * (lorentzian - gaussian),
        ))

    candidates = []
    for mix in (0.1, 0.5, 0.9):
        initial = [center, np.clip(width, 2 * spacing, 0.9 * span), height, max(0, baseline), slope, mix]
        result = least_squares(
            residual, initial, jac=jacobian, bounds=bounds, x_scale="jac",
            ftol=1e-11, xtol=1e-11, gtol=1e-11, max_nfev=500,
        )
        if result.success and not result.active_mask[:3].any() and np.isfinite(result.x).all():
            candidates.append(result)
    if not candidates:
        return None

    best = min(candidates, key=lambda result: result.cost)
    fit = dict(zip(PARAMETERS, best.x, strict=True))
    fit["rmse"] = np.sqrt(np.mean(best.fun ** 2))
    return fit


def typescript_fixture():
    angles, temperatures, intensities = load_measurements()
    lines = [
        "// Generated by derive-xrd-peak-fits.py from the catalog's measured scans.",
        "import type { XrdPeakData } from './XrdPeakTracker'",
        "import measurements from './waterfall/xrd-measurements.json'",
        "",
        "export const xrdPeakSource = {",
        "  label: 'Adeel Zafar, Harvard Dataverse',",
        "  href: 'https://doi.org/10.7910/DVN/ACPWBG',",
        "  description: 'Three local diffraction peaks fitted independently in 16 measured DyNiC₂ scans from 10.91 to 294.11 K.',",
        "  license: 'CC0 1.0',",
        "  licenseUrl: 'https://creativecommons.org/publicdomain/zero/1.0/',",
        "}",
        "",
        "export const xrdPeakData = {",
        "  angleDeg: measurements.spectralBins,",
        "  scans: measurements.scanValues.map((temperatureK, index) => ({",
        "    temperatureK,",
        "    intensity: measurements.intensityRows[index],",
        "  })),",
        "  peaks: [",
    ]
    for identifier, label, (lo, hi) in WINDOWS:
        mask = (angles >= lo) & (angles <= hi)
        lines.extend([
            "    {",
            f"      id: '{identifier}',",
            f"      label: '{label}',",
            f"      windowDeg: [{lo}, {hi}],",
            "      fits: [",
        ])
        for temperature, intensity in zip(temperatures, intensities, strict=True):
            fit = peak_fit(angles[mask], intensity[mask])
            if fit is None:
                lines.append("        null,")
                print(f"Rejected {identifier} fit at {temperature:g} K.", file=sys.stderr)
            else:
                properties = ", ".join(f"{name}: {value:.10g}" for name, value in fit.items())
                lines.append(f"        {{ {properties} }},")
        lines.extend(["      ],", "    },"])
    lines.extend(["  ],", "} satisfies XrdPeakData"])
    return "\n".join(lines)


if __name__ == "__main__":
    print(typescript_fixture())
