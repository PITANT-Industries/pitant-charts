"""Rebuild the sphericity fixture from Table 2 of Kim et al. (2019), CC BY 4.0.

Download the article XML from
https://www.ebi.ac.uk/europepmc/webservices/rest/PMC6915525/fullTextXML.
Run uv run derive-response-surface.py PMC6915525.xml > response-surface-data.ts.
"""

import argparse
import hashlib
from decimal import Decimal
from pathlib import Path
from xml.etree import ElementTree

import numpy as np


SOURCE_DOI = "10.3390/foods8110578"
SOURCE_SHA256 = "e64049a16f31c597830cfeb145cadc750c0aea16e566f893b32bf006cc0512de"


def observations(article):
    table = article.find('.//table-wrap[@id="foods-08-00578-t002"]/table')
    headings = tuple("".join(cell.itertext()).strip() for cell in table.findall("thead/tr")[-1])
    if headings != ("X1", "X2", "X1", "X2", "Y1", "Y2", "Y3"):
        raise ValueError("Unexpected factor and response columns in Table 2.")
    observations = []
    for row in table.findall("tbody/tr"):
        columns = ["".join(cell.itertext()).strip() for cell in row]
        run, _, _, temperature, minutes, _, _, sphericity = columns[-8:]
        observations.append((int(run), Decimal(temperature), Decimal(minutes), Decimal(sphericity)))
    if [run for run, *_ in observations] != list(range(1, 12)):
        raise ValueError("Expected eleven distinct experimental runs in source order.")
    return observations


def fit_quadratic(rows):
    _, temperatures, times, measured = np.asarray(rows, dtype=np.float64).T
    # Center and scale the physical factors before solving the equal-weight fit.
    u = (temperatures - 70) / 30
    v = (times - 32.5) / 27.5
    design = np.column_stack((np.ones_like(u), u, v, u * u, u * v, v * v))
    coefficients, _, rank, _ = np.linalg.lstsq(design, measured, rcond=None)
    if rank != design.shape[1]:
        raise ValueError("The experimental runs do not identify all six quadratic terms.")
    return coefficients


def typescript_fixture(path):
    raw = path.read_bytes()
    if hashlib.sha256(raw).hexdigest() != SOURCE_SHA256:
        raise ValueError("Article XML does not match the Europe PMC snapshot used here.")
    article = ElementTree.fromstring(raw)
    if article.findtext('.//article-id[@pub-id-type="doi"]') != SOURCE_DOI:
        raise ValueError("Unexpected article DOI.")
    rows = observations(article)
    coefficients = [f"{coefficient:.12f}" for coefficient in fit_quadratic(rows)]
    lines = [
        "// Generated by derive-response-surface.py from Table 2 of Kim et al. (2019).",
        "// The adapted measurements are available under CC BY 4.0. See THIRD_PARTY_NOTICES.md.",
        "import type { ResponseSurfaceData } from './ResponseSurface'",
        "",
        "const [intercept, temperatureSlope, timeSlope, temperatureSquare, interaction, timeSquare] = [",
        f"  {', '.join(coefficients[:3])},",
        f"  {', '.join(coefficients[3:])},",
        "] as const",
        "",
        "export const responseSurfaceSource = {",
        "  label: 'Kim et al., calcium alginate bead experiments',",
        f"  href: 'https://doi.org/{SOURCE_DOI}',",
        "  description: 'Each run reports the sphericity averaged over five beads, measured as the minor-to-major diameter ratio expressed as a percentage.',",
        "  license: 'CC BY 4.0',",
        "  licenseUrl: 'https://creativecommons.org/licenses/by/4.0/',",
        "}",
        "",
        "export const responseSurfaceData = {",
        "  xAxis: { label: 'Heating temperature', unit: '°C' },",
        "  yAxis: { label: 'Heating time', unit: 'min' },",
        "  responseAxis: { label: 'Sphericity', unit: '%' },",
        "  trials: [",
    ]
    for run, temperature, time, response in rows:
        lines.append(f"    {{ id: 'run-{run:02d}', x: {temperature}, y: {time}, response: {response} }},")
    lines.extend([
        "  ],",
        "  evaluate(temperature, time) {",
        "    const u = (temperature - 70) / 30",
        "    const v = (time - 32.5) / 27.5",
        "    return intercept + temperatureSlope * u + timeSlope * v +",
        "      temperatureSquare * u * u + interaction * u * v + timeSquare * v * v",
        "  },",
        "  initialPosition: [70, 32.5],",
        "  sectionAxis: 'x',",
        "} satisfies ResponseSurfaceData",
    ])
    return "\n".join(lines)


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("article_xml", type=Path)
    print(typescript_fixture(parser.parse_args().article_xml))
