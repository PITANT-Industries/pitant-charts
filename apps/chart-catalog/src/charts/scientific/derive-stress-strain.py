"""Rebuild the measured aluminum tensile fixture.

Download dataset EN AW-2618A.xlsx from https://doi.org/10.5281/zenodo.10377164.
Run uv run derive-stress-strain.py path/to/workbook.xlsx > stress-strain-data.ts.
"""

import argparse
import hashlib
import io
import math
from pathlib import Path
from statistics import linear_regression

from openpyxl import load_workbook


WORKBOOK_SHA256 = "1d6608e41f8def1dcb6d560c0837aff9176c55064424d030d3dda1a3aa556969"
TESTS = (
    ("t61", "T61", "ABR5RTzl1"),
    ("aged-160c", "T61 + 15,000 h at 160 °C", "ABR10RTzl1"),
    ("aged-190c", "T61 + 15,000 h at 190 °C", "ABR8RTzl1"),
)
HEADER = ("Time [s]", "Engineering strain e [mm/mm]", "Engineering stress R [MPa]")
FIT_START = 0.0005
FIT_END = 0.0015
OFFSET_STRAIN = 0.002
DENSE_END = 0.012
DENSE_STEP = 0.00005
TENSILE_STEP = 0.0004


def read_curve(worksheet):
    rows = worksheet.iter_rows(values_only=True)
    if next(rows) != HEADER:
        raise ValueError(f"Unexpected stress–strain columns in {worksheet.title}.")
    curve = []
    peak_stress = -math.inf
    final_strain = -math.inf
    previous_time = -math.inf
    for time, strain, stress in rows:
        if not all(map(math.isfinite, (time, strain, stress))) or time <= previous_time:
            raise ValueError(f"Inconsistent chronological measurements in {worksheet.title}.")
        previous_time = time
        peak_stress = max(peak_stress, stress)
        final_strain = strain
        # Keep the first observation at a new high strain. Do not reorder or average reversals.
        if not curve or strain > curve[-1][0]:
            curve.append((strain, stress))
    if not curve or curve[-1][0] != final_strain or max(stress for _, stress in curve) != peak_stress:
        raise ValueError(f"The monotonic loading curve must retain the measured peak and endpoint for {worksheet.title}.")
    return curve


def elastic_fit(curve):
    fit_points = [(strain, stress) for strain, stress in curve if FIT_START <= strain <= FIT_END]
    strains, stresses = zip(*fit_points, strict=True)
    return linear_regression(strains, stresses)


def proof_bracket(curve, fit):
    previous = None
    for index, (strain, stress) in enumerate(curve):
        if strain < FIT_END:
            continue
        residual = stress - (fit.slope * (strain - OFFSET_STRAIN) + fit.intercept)
        if previous is not None and previous > 0 >= residual:
            return index - 1, index
        previous = residual
    raise ValueError("No 0.2% proof-stress crossing in the measured curve.")


def render_points(curve, fit):
    proof_before, proof_after = proof_bracket(curve, fit)
    elastic_indices = [index for index, (strain, _) in enumerate(curve) if FIT_START <= strain <= FIT_END]
    peak = max(range(len(curve)), key=lambda index: curve[index][1])
    indices = {0, len(curve) - 1, peak, proof_before, proof_after, elastic_indices[0], elastic_indices[-1]}
    last_bin = None
    for index, (strain, _) in enumerate(curve):
        if strain < DENSE_END:
            bin_number = int(strain / DENSE_STEP)
        else:
            bin_number = int(DENSE_END / DENSE_STEP) + int((strain - DENSE_END) / TENSILE_STEP)
        if bin_number != last_bin:
            indices.add(index)
            last_bin = bin_number
    return [curve[index] for index in sorted(indices)]


def typescript_fixture(path):
    raw = path.read_bytes()
    if hashlib.sha256(raw).hexdigest() != WORKBOOK_SHA256:
        raise ValueError("Workbook does not match the published EN AW-2618A snapshot.")
    workbook = load_workbook(io.BytesIO(raw), read_only=True, data_only=True)
    try:
        overview = workbook["Tensiletest overview"]
        if overview["G1"].value != "Elongation after \nfracture A [%]":
            raise ValueError("Expected percentage elongation after fracture in the tensile overview.")
        elongations = {
            row[0]: row[6]
            for row in overview.iter_rows(min_row=2, max_col=7, values_only=True)
        }
        lines = [
            "// Generated by derive-stress-strain.py from three measured EN AW-2618A tensile tests.",
            "// The adapted measurement data are available under CC BY 4.0. See THIRD_PARTY_NOTICES.md.",
            "import type { StressStrainData } from './StressStrainComparison'",
            "",
            "export const stressStrainSource = {",
            "  label: 'Philipp von Hartrott and Birgit Skrotzki, Fraunhofer IWM and BAM',",
            "  href: 'https://doi.org/10.5281/zenodo.10377164',",
            "  description: 'Measured EN AW-2618A engineering stress and strain at 20 °C and 0.0001 s⁻¹. The three specimens share the DIN 50125 B6×30 geometry.',",
            "  license: 'CC BY 4.0',",
            "  licenseUrl: 'https://creativecommons.org/licenses/by/4.0/',",
            "}",
            "",
            "export const stressStrainData = {",
            "  curves: [",
        ]
        for identifier, label, sheet in TESTS:
            curve = read_curve(workbook[sheet])
            fit = elastic_fit(curve)
            elongation = elongations[sheet]
            if not isinstance(elongation, (int, float)) or not math.isfinite(elongation) or elongation < 0:
                raise ValueError(f"Missing valid elongation after fracture for {sheet}.")
            lines.extend([
                "    {",
                f"      // {sheet} in dataset EN AW-2618A.xlsx.",
                f"      id: '{identifier}',",
                f"      label: '{label}',",
                f"      elongationAfterFracture: {elongation},",
                "      elasticFit: {",
                f"        startStrain: {FIT_START}, endStrain: {FIT_END},",
                f"        modulusMpa: {fit.slope}, interceptMpa: {fit.intercept},",
                "      },",
                "      points: [",
            ])
            for strain, stress in render_points(curve, fit):
                lines.append(f"        {{ strain: {strain}, stressMpa: {stress} }},")
            lines.extend(["      ],", "    },"])
        lines.extend(["  ],", "} satisfies StressStrainData"])
        return "\n".join(lines)
    finally:
        workbook.close()


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("workbook", type=Path, help="Published dataset EN AW-2618A.xlsx")
    print(typescript_fixture(parser.parse_args().workbook))
