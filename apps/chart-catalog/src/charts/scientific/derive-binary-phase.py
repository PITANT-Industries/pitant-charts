"""Extract Ag–Cu boundary samples from the CC BY 4.0 ORCHID-Diagrams v2026.10 release.

Download AgCu-00Moo.json from https://data.orchid-project.org/phase-diagrams/sgte/AgCu-00Moo.json
or extract phase-diagrams/sgte/AgCu-00Moo.json from https://doi.org/10.5281/zenodo.23735859.
Run python3 derive-binary-phase.py path/to/AgCu-00Moo.json > binary-phase-data.ts.
"""

import argparse
from bisect import bisect_left
from decimal import Decimal
import hashlib
import json
from pathlib import Path


SOURCE_SHA256 = "f98c7b1dda9a2406107436863af48faac006bc6576316a6a1b615a2bfb499178"
TDB_SHA256 = "1e55749c7312290300c9c5fa7b53b7cc4b6751f5e4be8d499617455a722fa46d"
KELVIN_OFFSET = Decimal("273.15")
DISPLAY_MIN = 300
DISPLAY_MAX = 1125


def boundary(path):
    points = sorted((temperature - KELVIN_OFFSET, Decimal(fraction) * 100)
                    for temperature, fraction in zip(path["T"], path["x"], strict=True))
    if any(left[0] >= right[0] for left, right in zip(points, points[1:])):
        raise ValueError(f"Non-increasing temperatures on {path['phase']} boundary.")
    return points


def clip_solvus(points):
    lower_index = bisect_left(points, (DISPLAY_MIN, 0))
    if points[lower_index][0] == DISPLAY_MIN:
        return points[lower_index:]
    lower_t, lower_x = points[lower_index - 1]
    upper_t, upper_x = points[lower_index]
    amount = (DISPLAY_MIN - lower_t) / (upper_t - lower_t)
    exact_floor = round(lower_x + amount * (upper_x - lower_x), 8)
    return [(Decimal(DISPLAY_MIN), exact_floor), *points[lower_index:]]


def branch_coordinates(diagram):
    regions = diagram["regions"]
    # Regions 0 and 2 trace coincident pure-element lines. Regions 4 and 5 overlap
    # the complete FCC miscibility gap in regions 6 and 7, which are identical.
    if regions[6] != regions[7]:
        raise ValueError("Expected the two identical complete FCC solvus paths.")
    left_melt, right_melt = ({path["phase"]: boundary(path) for path in regions[index]} for index in (1, 3))
    # The local FCC composition-set suffix can switch between the invariant and mapped paths.
    left_solvus, right_solvus = sorted((boundary(path) for path in regions[6]), key=lambda path: path[-1][1])
    return {
        "leftLiquidus": left_melt["LIQUID"],
        "rightLiquidus": right_melt["LIQUID"],
        "leftSolidus": left_melt["FCC_A1"],
        "rightSolidus": right_melt["FCC_A1"],
        "leftSolvus": clip_solvus(left_solvus),
        "rightSolvus": clip_solvus(right_solvus),
    }


def validate_joins(branches, eutectic, left_solid, liquid, right_solid):
    if branches["leftLiquidus"][0] != (eutectic, liquid) or branches["rightLiquidus"][0] != (eutectic, liquid):
        raise ValueError("Liquidus paths must meet at the invariant liquid composition.")
    for side, solid, pure in (("left", left_solid, 0), ("right", right_solid, 100)):
        solidus, solvus, liquidus = (branches[side + name] for name in ("Solidus", "Solvus", "Liquidus"))
        if solidus[0] != solvus[-1] or solidus[0] != (eutectic, solid):
            raise ValueError(f"The {side} solidus and solvus must meet at the invariant solid composition.")
        if solidus[-1] != liquidus[-1] or solidus[-1][1] != pure:
            raise ValueError(f"The {side} solidus and liquidus must meet at pure melting.")
        if solvus[0][0] != DISPLAY_MIN or liquidus[-1][0] >= DISPLAY_MAX:
            raise ValueError(f"The {side} paths do not match the display domain.")


def number(value):
    return format(value.normalize(), "f")


def typescript_fixture(path):
    raw = path.read_bytes()
    if hashlib.sha256(raw).hexdigest() != SOURCE_SHA256:
        raise ValueError("Input JSON does not match the published ORCHID-Diagrams v2026.10 snapshot.")
    diagram = json.loads(raw, parse_float=Decimal)
    if (diagram["elements"] != ["Ag", "Cu"] or diagram["x_component"] != "CU"
            or diagram["sha256"] != TDB_SHA256 or diagram["status"] != "ok"):
        raise ValueError("Unexpected assessed system, composition axis, or model.")

    invariant, = diagram["invariants"]
    eutectic = invariant["T"] - KELVIN_OFFSET
    left_solid, right_solid = sorted(point["x"] * 100 for point in invariant["points"]
                                     if point["phase"].startswith("FCC_A1"))
    liquid, = (point["x"] * 100 for point in invariant["points"] if point["phase"] == "LIQUID")
    branches = branch_coordinates(diagram)
    validate_joins(branches, eutectic, left_solid, liquid, right_solid)

    lines = [
        "// Generated by derive-binary-phase.py from the CC BY 4.0 ORCHID-Diagrams v2026.10 release.",
        "// The adapted Ag–Cu model data retain attribution in THIRD_PARTY_NOTICES.md.",
        "import type { BinaryPhaseDiagramData } from './BinaryPhaseDiagram'",
        "",
        "export const binaryPhaseSource = {",
        "  label: 'Arróyave, Saal, and Shin, ORCHID-Diagrams',",
        "  href: 'https://doi.org/10.5281/zenodo.23735859',",
        "  description: 'Ag–Cu equilibrium calculated at 1 atm with pycalphad 0.11.2 from the Moon et al. assessment in the SGTE binary collection.',",
        "  license: 'CC BY 4.0',",
        "  licenseUrl: 'https://creativecommons.org/licenses/by/4.0/',",
        "}",
        "",
        "export const binaryPhaseData = {",
        "  components: ['Ag', 'Cu'],",
        "  compositionUnit: 'at. %',",
        f"  temperatureDomain: [{DISPLAY_MIN}, {DISPLAY_MAX}],",
        "  eutectic: {",
        f"    temperatureC: {number(eutectic)},",
        f"    leftSolid: {number(left_solid)},",
        f"    liquid: {number(liquid)},",
        f"    rightSolid: {number(right_solid)},",
        "  },",
        "  branches: {",
    ]
    for name, points in branches.items():
        lines.append(f"    {name}: [")
        for temperature, composition in points:
            lines.append(f"      {{ composition: {number(composition)}, temperatureC: {number(temperature)} }},")
        lines.append("    ],")
    lines.extend(["  },", "} satisfies BinaryPhaseDiagramData"])
    return "\n".join(lines)


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("source_json", type=Path)
    print(typescript_fixture(parser.parse_args().source_json))
