"""Rebuild the measured NIST Allan deviation fixture.

Download both phase CSVs from https://doi.org/10.18434/M32206.
Run python3 derive-allan-deviation.py path/to/downloads > allan-deviation-data.ts.
"""

import argparse
import hashlib
import math
from pathlib import Path


DATASET_URL = "https://doi.org/10.18434/M32206"
REUSE_URL = "https://www.nist.gov/open/license"
PHASE_SAMPLES = 44_002
SAMPLE_SECONDS = 1
AVERAGING_FACTORS = sorted({round(10 ** (step / 10)) for step in range(41)})
OPTICAL = {
    "filename": "Yb_Clock_phase(rad) vs time.csv",
    "sha256": "c00f2c5c03c3ef0cf346de9917b66800eccd4147cc86af88feae9d02725baad9",
    "radians_per_unit": 1.0,
    "nominal_carrier_hz": 259e12,
}
MICROWAVE = {
    "filename": "10GHz_phase(mrad) vs time.csv",
    "sha256": "9d715e33e8440dc7b84833ee51a48884e7e7091cc632f482ab2812fc466793be",
    "radians_per_unit": 1e-3,
    "nominal_carrier_hz": 10e9,
}


def read_time_error(directory, source):
    path = directory / source["filename"]
    raw = path.read_bytes()
    if hashlib.sha256(raw).hexdigest() != source["sha256"]:
        raise ValueError(f"{path.name} does not match NIST's published SHA-256.")

    time_error = []
    radians_to_time = source["radians_per_unit"] / (math.tau * source["nominal_carrier_hz"])
    for index, line in enumerate(raw.decode("ascii").splitlines()):
        elapsed, phase = map(float, line.split())
        if elapsed != index * SAMPLE_SECONDS or not math.isfinite(phase):
            raise ValueError(f"Invalid or missing phase measurement in {path.name} at row {index + 1}.")
        time_error.append(phase * radians_to_time)
    if len(time_error) != PHASE_SAMPLES:
        raise ValueError(f"Unexpected number of phase measurements in {path.name}.")
    return time_error


def overlapping_allan_deviation(time_error, factor):
    tau_seconds = factor * SAMPLE_SECONDS
    pairs = len(time_error) - 2 * factor
    squared_sum = math.fsum(
        ((last - middle) - (middle - first)) ** 2
        for first, middle, last in zip(time_error, time_error[factor:], time_error[2 * factor:])
    )
    return tau_seconds, math.sqrt(squared_sum / (2 * pairs * tau_seconds ** 2)), pairs


def typescript_fixture(directory):
    optical = read_time_error(directory, OPTICAL)
    microwave = read_time_error(directory, MICROWAVE)
    residual = [mw - ow for ow, mw in zip(optical, microwave, strict=True)]
    curves = (
        ("optical", "Ytterbium optical beat", optical),
        ("microwave", "10 GHz microwave beat", microwave),
        ("residual", "Microwave − optical residual", residual),
    )

    lines = [
        "// Generated by derive-allan-deviation.py from the NIST phase recordings.",
        "import type { AllanDeviationData } from './AllanDeviation'",
        "",
        "export const allanDeviationSource = {",
        "  label: 'Takuma Nakamura et al., National Institute of Standards and Technology',",
        f"  href: '{DATASET_URL}',",
        "  description: 'Derived from 44,002 synchronized one-second phase samples of the paired ytterbium clocks and their 10 GHz microwave outputs. The residual is the difference of the two time-error records.',",
        "  license: 'NIST data terms',",
        f"  licenseUrl: '{REUSE_URL}',",
        "}",
        "",
        "export const allanDeviationData = {",
        "  quantity: 'fractional frequency',",
        "  curves: [",
    ]
    for identifier, label, phase in curves:
        lines.extend([
            "    {",
            f"      id: '{identifier}',",
            f"      label: '{label}',",
            "      points: [",
        ])
        for factor in AVERAGING_FACTORS:
            tau_seconds, deviation, pairs = overlapping_allan_deviation(phase, factor)
            lines.append(
                f"        {{ tauSeconds: {tau_seconds}, deviation: {deviation:.16g}, pairs: {pairs} }},"
            )
        lines.extend(["      ],", "    },"])
    lines.extend(["  ],", "} satisfies AllanDeviationData"])
    return "\n".join(lines)


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("directory", type=Path, help="Directory containing the published NIST phase records")
    print(typescript_fixture(parser.parse_args().directory))
