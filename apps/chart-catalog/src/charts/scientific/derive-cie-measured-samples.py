"""Compute CIE 1931 2° chromaticities for the 99 CIE fidelity samples under D65.

Download the files named in CHECKSUMS from
https://files.cie.co.at/Publications-datasets/ into one directory.
Run python3 derive-cie-measured-samples.py INPUT_DIRECTORY > cie-measured-samples.ts.
"""

import argparse
import csv
from decimal import Decimal, localcontext
import hashlib
import json
from pathlib import Path


CHECKSUMS = {
    "CIE_srf_cfi_1nm.csv": "32327de84b4bb8715a2b2f1bce3f5d2eca6276a44bde19c93c6f0aad5742db63",
    "CIE_srf_cfi_1nm.csv_metadata_v2.json": "a78d61de4cfc9b8c8c03b199db7109bf2e0cd82c4a583b60a4bc0b186c4fd0c6",
    "CIE_std_illum_D65.csv": "e76f210bffff3d552ef7113025da5f325d5dfec200dd4b878b1a2f3a507032cb",
    "CIE_xyz_1931_2deg.csv": "fa663e3535a7e0763a745993a1f0a192eb0275ac46ad2d1befd7626841e713c1",
}


def verified_file(directory, name):
    content = (directory / name).read_bytes()
    if hashlib.sha256(content).hexdigest() != CHECKSUMS[name]:
        raise ValueError(f"{name} does not match the checksum used to generate the fixture.")
    return content


def spectral_table(directory, name, first, last, columns):
    content = verified_file(directory, name).decode("ascii")
    rows = list(csv.reader(content.splitlines()))
    if [int(row[0]) for row in rows] != list(range(first, last + 1)):
        raise ValueError(f"Expected every 1 nm wavelength from {first} to {last} in {name}.")
    if any(len(row) != columns + 1 for row in rows):
        raise ValueError(f"Expected {columns} spectral columns in {name}.")
    return {int(row[0]): tuple(Decimal(value) for value in row[1:]) for row in rows}


def typescript_fixture(directory):
    radiance = spectral_table(directory, "CIE_srf_cfi_1nm.csv", 380, 780, 99)
    illuminant = spectral_table(directory, "CIE_std_illum_D65.csv", 300, 830, 1)
    observer = spectral_table(directory, "CIE_xyz_1931_2deg.csv", 360, 830, 3)
    metadata = json.loads(verified_file(directory, "CIE_srf_cfi_1nm.csv_metadata_v2.json"))
    headings = metadata["datatableInfo"]["columnHeaders"][1:]
    if [heading["title"] for heading in headings] != [f"Sample #{number}" for number in range(1, 100)]:
        raise ValueError("Expected the 99 CES columns in their published sample order.")

    lines = [
        "// Generated by derive-cie-measured-samples.py from official CIE spectral tables.",
        "// The adapted data are available under CC BY-SA 4.0. See THIRD_PARTY_NOTICES.md.",
        "import type { CieColorSample } from './CieChromaticityDiagram'",
        "",
        "export const cieMeasuredSamples: readonly CieColorSample[] = [",
    ]
    with localcontext() as context:
        context.prec = 50
        # The common illuminant normalization and the 1 nm interval cancel in xy.
        weights = {wavelength: tuple(illuminant[wavelength][0] * v for v in observer[wavelength])
                   for wavelength in radiance}
        for sample, heading in enumerate(headings, start=1):
            xyz = [sum(row[sample - 1] * weights[wavelength][channel]
                       for wavelength, row in radiance.items()) for channel in range(3)]
            total = sum(xyz)
            x, y = (coordinate / total for coordinate in xyz[:2])
            category = heading["description"].split(":", 1)[1].strip()
            label = json.dumps(f"CES {sample:02d} · {category}", ensure_ascii=False)
            lines.append(f"  {{ id: 'ces-{sample:02d}', label: {label}, xy: [{x:.9f}, {y:.9f}] }},")
    return "\n".join([*lines, "]"])


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("input_directory", type=Path)
    print(typescript_fixture(parser.parse_args().input_directory))
