"""Rebuild the measured phase-plane fixture.

Download the three named CSVs from the raw_data directory at SOURCE_URL:
https://github.com/EnzeXu/Damped_Pendulum_Dataset/tree/cbf82673641ecd65e902ad5c38a048387649a2a0/raw_data
Run python3 derive-phase-plane.py path/to/downloads > phase-plane-data.ts.
"""

import argparse
import csv
import hashlib
import io
import math
from pathlib import Path


SOURCE_URL = "https://github.com/EnzeXu/Damped_Pendulum_Dataset/tree/cbf82673641ecd65e902ad5c38a048387649a2a0"
LICENSE_URL = SOURCE_URL.replace("/tree/", "/blob/") + "/LICENSE"
SOURCE_RATE_HZ = 100
DISPLAY_STRIDE = 4
DURATION_SECONDS = 16
TIME_COLUMN = "Time (s) Run #1"
POSITION_COLUMN = "Angle (rad) Run #1"
VELOCITY_COLUMN = "Angular Velocity (rad/s) Run #1"

# Each start row is the last zero-velocity sample before sustained inward motion.
RECORDINGS = (
    {
        "id": "air-only",
        "label": "Air only",
        "filename": "len5_cond1_2.csv",
        "start_row": 344,
        "sha256": "637c37cdd84b9bba424555a4348eb4048b4c07bbb33db9d029967e0710646266",
    },
    {
        "id": "small-baffle",
        "label": "Small paper baffle",
        "filename": "len5_cond2_2.csv",
        "start_row": 298,
        "sha256": "fd6370950cfa601953f71b83a5b4e3df3c3d58b6e4ea38e07f7e10bd9710bbd0",
    },
    {
        "id": "large-baffle",
        "label": "Large paper baffle",
        "filename": "len5_cond3_1.csv",
        "start_row": 357,
        "sha256": "b89aae6d6d6747660f2378ab732b9691cee9a3541eebc6f4f46d3202d12d9c50",
    },
)


def read_samples(directory, recording):
    path = directory / recording["filename"]
    raw = path.read_bytes()
    if hashlib.sha256(raw).hexdigest() != recording["sha256"]:
        raise ValueError(f"{path.name} does not match the pinned recording hash.")
    rows = list(csv.DictReader(io.StringIO(raw.decode("utf-8-sig"))))
    start = recording["start_row"]
    end = start + SOURCE_RATE_HZ * DURATION_SECONDS
    if len(rows) <= end or float(rows[start][VELOCITY_COLUMN]) != 0:
        raise ValueError(f"Missing complete release window in {path.name}.")

    samples = []
    for index in range(start, end + 1):
        row = rows[index]
        time = float(row[TIME_COLUMN])
        angle = float(row[POSITION_COLUMN])
        velocity = float(row[VELOCITY_COLUMN])
        if time != index / SOURCE_RATE_HZ or not all(map(math.isfinite, (angle, velocity))):
            raise ValueError(f"Unexpected measurement at row {index + 1} of {path.name}.")
        if (index - start) % DISPLAY_STRIDE == 0:
            samples.append(((index - start) / SOURCE_RATE_HZ, angle, velocity))
    return samples


def typescript_fixture(directory):
    lines = [
        "// SPDX-License-Identifier: Apache-2.0",
        "// Generated by derive-phase-plane.py from the Damped Pendulum Dataset.",
        "// Source trials were excerpted, rebased to elapsed time, and sampled at 25 Hz.",
        "import type { PhasePlaneData } from './PhasePlane'",
        "",
        "export const phasePlaneSource = {",
        "  label: 'Enze Xu et al., Damped Pendulum Dataset',",
        f"  href: '{SOURCE_URL}',",
        "  description: 'Measured free decay of a 0.607 m pendulum in air and with two paper baffles. Angle and angular velocity come from the rotary sensor recordings.',",
        "  license: 'Apache-2.0',",
        f"  licenseUrl: '{LICENSE_URL}',",
        "}",
        "",
        "export const phasePlaneData = {",
        "  positionLabel: 'Angular displacement, θ',",
        "  positionUnit: 'rad',",
        "  velocityLabel: 'Angular velocity, ω',",
        "  velocityUnit: 'rad/s',",
        "  runs: [",
    ]
    for recording in RECORDINGS:
        start_time = recording["start_row"] / SOURCE_RATE_HZ
        lines.extend([
            "    {",
            f"      // {recording['filename']}, starting at sensor time {start_time:.2f} s.",
            f"      id: '{recording['id']}',",
            f"      label: '{recording['label']}',",
            "      samples: [",
        ])
        for time, angle, velocity in read_samples(directory, recording):
            lines.append(f"        {{ timeSeconds: {time:g}, position: {angle:g}, velocity: {velocity:g} }},")
        lines.extend(["      ],", "    },"])
    lines.extend(["  ],", "} satisfies PhasePlaneData"])
    return "\n".join(lines)


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("directory", type=Path, help="Directory containing the three pinned raw CSVs")
    print(typescript_fixture(parser.parse_args().directory))
