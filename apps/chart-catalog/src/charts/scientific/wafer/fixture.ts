export const simulatedWaferData: SpatialDefectData = {
  bins: [
    { id: 'parametric-fail', label: 'Parametric fail' },
    { id: 'functional-fail', label: 'Functional fail' },
  ],
  wafers: simulatedWafers.map(({ id, label, batch, pattern, seed, inPattern }): Wafer => {
    const dies: Die[] = []
    for (let row = 0; row < 19; row++) {
      for (let column = 0; column < 20; column++) {
        const x = column * geometry.pitchX + geometry.originX
        const y = row * geometry.pitchY + geometry.originY
        if (Math.hypot(Math.abs(x) + geometry.pitchX / 2, Math.abs(y) + geometry.pitchY / 2) > geometry.radius) continue

        const code = (row * 53 + column * 97 + seed) % 149
        if (code < 2) dies.push({ row, column, status: 'missing' })
        else if (code < 6) dies.push({ row, column, status: 'untested' })
        else if (inPattern(x, y)) {
          dies.push({ row, column, status: 'fail', bin: code % 5 === 0 ? 'functional-fail' : 'parametric-fail' })
        } else if (code % 61 === 0) dies.push({ row, column, status: 'fail', bin: 'functional-fail' })
        else dies.push({ row, column, status: 'pass' })
      }
    }
    return { id, label, batch, pattern, geometry, dies }
  }),
}
