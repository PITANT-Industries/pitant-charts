export const measuredWaferData: SpatialDefectData = {
  bins: [{ id: 'electrical-fail', label: 'Electrical fail' }],
  wafers: measuredMaps.map(({ id, label, batch, pattern, rows }): Wafer => {
    const dies: Die[] = []
    for (const [row, values] of rows.entries()) {
      for (const [column, value] of Array.from(values).entries()) {
        if (value === '1') dies.push({ row, column, status: 'pass' })
        if (value === '2') dies.push({ row, column, status: 'fail', bin: 'electrical-fail' })
      }
    }
    return {
      id,
      label,
      batch,
      pattern,
      geometry: {
        unit: 'die pitch',
        pitchX: 1,
        pitchY: 1,
        originX: -Math.floor(rows[0].length / 2),
        originY: Math.floor(rows.length / 2),
        rowDirection: 'down',
      },
      dies,
    }
  }),
}

