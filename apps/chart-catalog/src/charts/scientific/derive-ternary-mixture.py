"""Rebuild the geopolymer mixture fixture from Xu et al. (2026), CC BY 4.0.

Download the article XML from
https://www.ebi.ac.uk/europepmc/webservices/rest/PMC13611231/fullTextXML.
Run uv run derive-ternary-mixture.py path/to/article.xml > ternary-mixture-data.ts.
"""

import argparse
from decimal import Decimal
import hashlib
from pathlib import Path
from xml.etree import ElementTree

import numpy as np


SOURCE_DOI = "10.3390/polym18182271"
SOURCE_SHA256 = "909bc331f10c27f892254f9866dc6e76c5c894b14cadff14900cd548090aa34a"


def table_rows(article, number, header):
    table = article.find(f'.//table-wrap[@id="polymers-18-02271-t{number:03d}"]/table')
    headings = tuple("".join(cell.itertext()).strip() for cell in table.findall("thead/tr/*"))
    if headings[:len(header)] != header:
        raise ValueError(f"Unexpected columns in source Table {number}.")
    return [tuple("".join(cell.itertext()).strip() for cell in row) for row in table.findall("tbody/tr")]


def observations(article):
    mixtures = table_rows(article, 2, ("Mix IDs", "GGBS", "FA", "RM"))
    strengths = table_rows(article, 3, ("Mix IDs", "fc (MPa)"))
    strength_by_id = {row[0]: Decimal(row[1].split()[0]) for row in strengths}
    if len(mixtures) != 10 or len(strengths) != 10 or set(strength_by_id) != {row[0] for row in mixtures}:
        raise ValueError("The source tables do not describe the same ten mixtures.")

    result = []
    for mixture, slag, ash, mud, *_ in mixtures:
        masses = tuple(map(Decimal, (slag, ash, mud)))
        if sum(masses) != Decimal("1213.80") or min(masses) < 0:
            raise ValueError(f"Unexpected total precursor mass for {mixture}.")
        fractions = tuple(mass / sum(masses) for mass in masses)
        result.append((mixture, fractions, strength_by_id[mixture]))
    return result


def fit_quadratic(rows):
    design = []
    measured = []
    for _, fractions, value in rows:
        a, b, c = map(float, fractions)
        design.append((a, b, c, a * b, a * c, b * c))
        measured.append(float(value))
    coefficients, _, rank, _ = np.linalg.lstsq(design, measured, rcond=None)
    if rank != 6:
        raise ValueError("The ten mixtures do not identify all six Scheffé quadratic terms.")
    return coefficients


def typescript_fixture(path):
    raw = path.read_bytes()
    if hashlib.sha256(raw).hexdigest() != SOURCE_SHA256:
        raise ValueError("Article XML does not match the published Europe PMC snapshot used here.")
    article = ElementTree.fromstring(raw)
    if article.findtext('.//article-id[@pub-id-type="doi"]') != SOURCE_DOI:
        raise ValueError("Unexpected document DOI.")
    rows = observations(article)
    model = ", ".join(f"{coefficient:.8f}" for coefficient in fit_quadratic(rows))
    lines = [
        "// Generated by derive-ternary-mixture.py from Tables 2 and 3 of Xu et al. (2026).",
        "// The adapted measurements are available under CC BY 4.0. See THIRD_PARTY_NOTICES.md.",
        "import type { TernaryMixtureData } from './TernaryMixtureMap'",
        "",
        "export const ternaryMixtureSource = {",
        "  label: 'Shuo Xu et al., geopolymer composite tests',",
        f"  href: 'https://doi.org/{SOURCE_DOI}',",
        "  description: 'Ten measured 28-day uniaxial compressive strengths of geopolymer mixes. The three shares are fractions of the dry binder mass.',",
        "  license: 'CC BY 4.0',",
        "  licenseUrl: 'https://creativecommons.org/licenses/by/4.0/',",
        "}",
        "",
        "export const ternaryMixtureData = {",
        "  components: ['Ground granulated blast-furnace slag', 'Fly ash', 'Red mud'],",
        "  shortComponents: ['Slag', 'Fly ash', 'Red mud'],",
        "  responseLabel: 'Compressive strength',",
        "  responseUnit: 'MPa',",
        "  observations: [",
    ]
    for marker, fractions, value in rows:
        composition = ", ".join(format(part, "f") for part in fractions)
        lines.append(f"    {{ id: '{marker}', fractions: [{composition}], value: {value} }},")
    lines.extend([
        "  ],",
        f"  model: [{model}],",
        "  colorDomain: [65, 115],",
        "} satisfies TernaryMixtureData",
    ])
    return "\n".join(lines)


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("article_xml", type=Path)
    print(typescript_fixture(parser.parse_args().article_xml))
