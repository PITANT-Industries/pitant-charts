"""Rebuild the measured S–N fixture from Jan Papuga et al.'s FABEST database.

Download FAB_v20261023.xlsm from https://doi.org/10.5281/zenodo.23603840 (CC BY 4.0).
Run uv run derive-fatigue-sn.py path/to/FAB_v20261023.xlsm > fatigue-sn-data.ts.
Openpyxl reads the cached workbook values without executing formulas or VBA.
"""

import argparse
import hashlib
import io
from pathlib import Path

from openpyxl import load_workbook


WORKBOOK_SHA256 = "3c5c21e0d5c3683855e6ee08d1579cb6a08074093335463eb882086fd355e31e"
CAMPAIGNS = ((60, "Setup 37", 12), (70, "Setup 35", 10))
CSV_SETTINGS = {
    "CUR_TYPE": 2,  # S–N curve
    "SRC_TYPE": 3,  # Raw data in numbers
    "LC1_MODE": 1,  # Axial tension–compression
    "LD1_TYPE": 1,  # Harmonic, constant amplitude
    "LD1_V1": "x1",  # D1 is the stress amplitude
    "LD1_V2": 0,  # Zero mean stress, R = −1
    "LC2_MODE": 0,  # No second loading channel
    "SP_LOADS": 1,  # Net section
    "END": 3,  # Complete break
}


def read_tests(worksheet, expected_count):
    rows = worksheet.iter_rows(max_col=15, values_only=True)
    next(rows)
    if next(rows)[7] != "tension-compression":
        raise ValueError(f"Unexpected loading channel in {worksheet.title}.")
    units = next(rows)
    if units[7:13] != (
        "amplitude [MPa]", "mean value [MPa]", "frequency [Hz]", "phase shift [deg]", "till END", "till break"
    ):
        raise ValueError(f"Unexpected test columns in {worksheet.title}.")
    if next(rows)[5] != f"{worksheet.title}_Rm":
        raise ValueError(f"Expected the separate static tensile entry in {worksheet.title}.")

    tests = {}
    for row in rows:
        specimen, lead, amplitude, mean, _, _, stop_cycles, break_cycles, status, _ = row[5:15]
        if specimen is None:
            break  # The blank row separates observations from the workbook's later regression tables.
        if not specimen.startswith(f"{worksheet.title}_") or specimen in tests:
            raise ValueError(f"Invalid point ID in {worksheet.title}: {specimen}.")
        if lead != amplitude or amplitude <= 0 or mean != 0 or type(stop_cycles) is not int or stop_cycles <= 0:
            raise ValueError(f"Invalid amplitude, mean stress, or cycle count for {specimen}.")
        if status == "finished" and break_cycles == stop_cycles:
            outcome = "failure"
        elif status == "interrupted" and break_cycles is None:
            outcome = "runout"
        else:
            raise ValueError(f"Inconsistent completion and break fields for {specimen}.")
        tests[specimen] = (amplitude, stop_cycles, outcome)
    if len(tests) != expected_count:
        raise ValueError(f"Unexpected specimen count for {worksheet.title}.")
    return tests


def check_csv(csv_fields, campaign_number, tests):
    column = csv_fields["CURVE_ID"].index(campaign_number)
    for field, expected in CSV_SETTINGS.items():
        if csv_fields[field][column] != expected:
            raise ValueError(f"Unexpected {field} in curve {campaign_number}.")
    prefix = f"FAB{campaign_number:03d}"
    remaining = dict(tests)
    for index in range(1, 61):
        mark = csv_fields[f"P{index}_MARK"][column]
        amplitude = csv_fields[f"D1_{index}"][column]
        if mark in (None, "Rm") and amplitude is None:
            continue
        specimen = f"{prefix}_{mark}"
        expected_amplitude, cycles, outcome = remaining.pop(specimen)
        expected_break = cycles if outcome == "failure" else None
        expected_flag = "I" if outcome == "runout" else None
        if (amplitude, csv_fields[f"I1_{index}"][column], csv_fields[f"I2_{index}"][column],
                csv_fields[f"I3_{index}"][column]) != (expected_amplitude, cycles, expected_break, expected_flag):
            raise ValueError(f"The original curve and CSV data disagree for {specimen}.")
    if remaining:
        raise ValueError(f"The CSV sheet is missing {len(remaining)} specimens from {prefix}.")


def typescript_fixture(path):
    raw = path.read_bytes()
    if hashlib.sha256(raw).hexdigest() != WORKBOOK_SHA256:
        raise ValueError("Workbook does not match the FABEST 2026-10-23 snapshot.")
    workbook = load_workbook(io.BytesIO(raw), read_only=True, data_only=True, keep_vba=False, keep_links=False)
    try:
        csv_fields = {row[1]: row[2:] for row in workbook["csv"].values if row[1] is not None}
        lines = [
            "// Generated by derive-fatigue-sn.py from the FABEST 2026-10-23 workbook.",
            "// The measured data subset is licensed under CC BY 4.0. See THIRD_PARTY_NOTICES.md.",
            "import type { FatigueSnData } from './FatigueSn'",
            "",
            "export const fatigueSnSource = {",
            "  label: 'Jan Papuga et al., FABEST benchmark',",
            "  href: 'https://doi.org/10.5281/zenodo.23603840',",
            "  description: 'Two measured axial fatigue campaigns on turned 42CrMo4 +QT hollow specimens at R = −1. Tests marked as interrupted retain their recorded stop counts.',",
            "  license: 'CC BY 4.0',",
            "  licenseUrl: 'https://creativecommons.org/licenses/by/4.0/',",
            "}",
            "",
            "export const fatigueSnData = {",
            "  stressLabel: 'Stress amplitude, σₐ',",
            "  series: [",
        ]
        for number, label, count in CAMPAIGNS:
            tests = read_tests(workbook[f"FAB{number:03d}"], count)
            check_csv(csv_fields, number, tests)
            lines.extend([
                "    {",
                f"      id: 'fab{number:03d}',",
                f"      label: '{label}',",
                "      stressRatio: -1,",
                "      tests: [",
            ])
            for specimen, (amplitude, cycles, outcome) in tests.items():
                lines.append(f"        {{ id: '{specimen}', stressMpa: {amplitude}, cycles: {cycles}, outcome: '{outcome}' }},")
            lines.extend(["      ],", "    },"])
        lines.extend(["  ],", "} satisfies FatigueSnData"])
        return "\n".join(lines)
    finally:
        workbook.close()


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("workbook", type=Path)
    print(typescript_fixture(parser.parse_args().workbook))
