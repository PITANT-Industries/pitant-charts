"""Rebuild the measured crack-growth fixture from Seitl et al. (2026), CC BY 4.0.

Download FCPR_Data_CMOD_a_Optical.xlsx from https://doi.org/10.5281/zenodo.21901500.
Run uv run derive-crack-growth.py path/to/workbook.xlsx > crack-growth-data.ts.
"""

import argparse
import hashlib
import io
import math
from pathlib import Path

from openpyxl import load_workbook


WORKBOOK_SHA256 = "9db8d7ad6a855e41ee3ab678395ae600d00743bfa023689effda6245cbb0d623"
SERIES = (("S460", 9, 77, 24), ("S690", 8, 154, 75), ("S960", 8, 212, 97))
UNITS = ("DK [MPam1/2]", "da/dN [mm/cycle]", "da/dN [mm/cycle]")
FIT_START = 10
FIT_END = 20


def read_cmod(worksheet, first_column, last_row, expected_count):
    rows = worksheet.iter_rows(
        min_col=first_column, max_col=first_column + 2, max_row=last_row, values_only=True
    )
    if not next(rows)[0].startswith("CMOD") or next(rows) != UNITS:
        raise ValueError(f"Unexpected CMOD columns for {worksheet.title}.")
    points = []
    for row_number, (delta_k, full_rate, selected_rate) in enumerate(rows, 3):
        # The adjacent source column retains the measurements the authors selected for comparison.
        if selected_rate is None:
            continue
        if (
            not all(isinstance(value, (int, float)) and math.isfinite(value) and value > 0
                    for value in (delta_k, selected_rate))
            or selected_rate != full_rate
        ):
            raise ValueError(f"Unexpected selected measurement in {worksheet.title} row {row_number}.")
        points.append((delta_k, selected_rate))
    points.sort(key=lambda point: point[0])
    if len(points) != expected_count or not (points[0][0] < FIT_START < FIT_END < points[-1][0]):
        raise ValueError(f"Unexpected observation count or ΔK coverage for {worksheet.title}.")
    return points


def typescript_fixture(path):
    raw = path.read_bytes()
    if hashlib.sha256(raw).hexdigest() != WORKBOOK_SHA256:
        raise ValueError("Workbook does not match the published Zenodo v2 snapshot.")
    workbook = load_workbook(io.BytesIO(raw), read_only=True, data_only=True, keep_links=False)
    try:
        lines = [
            "// Generated by derive-crack-growth.py from the Zenodo v2 crack-growth workbook.",
            "// The measurement subset is licensed under CC BY 4.0. See THIRD_PARTY_NOTICES.md.",
            "import type { CrackGrowthData } from './CrackGrowth'",
            "",
            "export const crackGrowthSource = {",
            "  label: 'Stanislav Seitl et al., high-strength steel crack growth',",
            "  href: 'https://doi.org/10.5281/zenodo.21901500',",
            "  description: 'Published CMOD measurements for S460, S690, and S960 compact-tension tests at 22 ± 1 °C and R = 0.1. The example fits a shared 10–20 MPa√m interval.',",
            "  license: 'CC BY 4.0',",
            "  licenseUrl: 'https://creativecommons.org/licenses/by/4.0/',",
            "}",
            "",
            "export const crackGrowthData = {",
            "  series: [",
        ]
        for grade, first_column, last_row, count in SERIES:
            points = read_cmod(workbook[grade], first_column, last_row, count)
            lines.extend([
                "    {",
                f"      id: '{grade.lower()}',",
                f"      label: '{grade}',",
                "      stressRatio: 0.1,",
                f"      fitRange: [{FIT_START}, {FIT_END}],",
                "      points: [",
            ])
            for delta_k, rate in points:
                lines.append(f"        {{ deltaK: {delta_k!r}, rateMmPerCycle: {rate!r} }},")
            lines.extend(["      ],", "    },"])
        lines.extend(["  ],", "} satisfies CrackGrowthData"])
        return "\n".join(lines)
    finally:
        workbook.close()


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("workbook", type=Path)
    print(typescript_fixture(parser.parse_args().workbook))
