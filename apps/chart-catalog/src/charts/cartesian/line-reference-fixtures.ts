export function referenceLineFixture(id: string): CartesianData | undefined {
  if (id === "line-segment") {
    const { categories, series: [visitors] } = fixtures["line-time-range"]();
    return { categories: categories.slice(-45), series: [{ ...visitors, values: visitors.values.slice(-45) }] };
  }
  if (id === "line-deadline-fills") {
    const { categories, series } = fixtures["line-weekends"]();
    return { categories, series: series.slice(2) };
  }
  const shared = {
    "line-band-fill": "line-band",
    "line-band-fade": "line-band",
    "line-band-edges": "line-band",
    "line-deadline": "line-weekends",
  } as Record<string, string>;
  const key = shared[id] ?? id;
  return Object.hasOwn(fixtures, key) ? fixtures[key]() : undefined;
}
