#!/usr/bin/env python3
"""Regenerate the example LC–MS feature and scan records with pyOpenMS 3.6.0."""

import argparse
import hashlib
import json
from pathlib import Path

import numpy as np
import pyopenms as oms


SOURCE_SHA256 = '61579b268be55f142d2136301ceb94adf1c919f7297bb9419f5dacd5e921fc5c'
SOURCE_COMMIT = '01540e638431426a39b4d7acce41a5e2c738b235'
SOURCE_RELATIVE_PATH = 'doc/pyopenms/src/data/Metabolomics_1.mzML'
SOURCE_URL = f'https://raw.githubusercontent.com/OpenMS/OpenMS/{SOURCE_COMMIT}/{SOURCE_RELATIVE_PATH}'
PPM = 10
RT_PADDING_SECONDS = 6


def configure(algorithm, **values):
    parameters = algorithm.getDefaults()
    for key, value in values.items():
        parameters.setValue(key, value)
    algorithm.setParameters(parameters)
    return algorithm


def detect_features(experiment):
    mass_traces = configure(
        oms.MassTraceDetection(), mass_error_ppm=float(PPM), noise_threshold_int=10000.0,
    ).run(experiment)
    elution_peaks = configure(
        oms.ElutionPeakDetection(), width_filtering='fixed',
    ).detectPeaks(mass_traces)
    features = oms.FeatureMap()
    configure(
        oms.FeatureFindingMetabo(), remove_single_traces=True, report_convex_hulls=True,
    ).run(elution_peaks, features)
    return sorted(features, key=lambda feature: (feature.getRT(), feature.getMZ()))


def convex_envelope(points):
    ordered = sorted(set(map(tuple, points.tolist())))

    def half(sequence):
        boundary = []
        for point in sequence:
            while len(boundary) >= 2:
                a, b = boundary[-2:]
                if (b[0] - a[0]) * (point[1] - a[1]) - (b[1] - a[1]) * (point[0] - a[0]) > 0:
                    break
                boundary.pop()
            boundary.append(point)
        return boundary

    if len(ordered) <= 2:
        return ordered
    return half(ordered)[:-1] + half(reversed(ordered))[:-1]


def extracted_samples(scans, minimum, maximum):
    for scan_id, rt, masses, intensities in scans:
        left = masses.searchsorted(minimum, side='left')
        right = masses.searchsorted(maximum, side='right')
        yield scan_id, rt, float(np.sum(intensities[left:right], dtype=np.float64))


def make_record(feature, index, scans):
    hulls = [convex_envelope(hull.getHullPoints()) for hull in feature.getConvexHulls()]
    centers = feature.getMetaValue('masstrace_centroid_mz')
    if len(hulls) != len(centers) or not all(hulls):
        raise ValueError('Every mass trace must carry its reported hull')
    trace_times = [rt for hull in hulls for rt, _ in hull]
    start = min(trace_times) - RT_PADDING_SECONDS
    end = max(trace_times) + RT_PADDING_SECONDS
    observed_scans = [entry for entry in scans if start <= entry[1] <= end]
    traces = []
    for ordinal, (mass, hull) in enumerate(zip(centers, hulls, strict=True)):
        delta = mass * PPM / 1e6
        lower, upper = mass - delta, mass + delta
        traces.append({
            'id': f'M+{ordinal}', 'mz': mass, 'hull': hull, 'mzWindow': (lower, upper),
            'samples': list(extracted_samples(observed_scans, lower, upper)),
        })
    return {
        'id': f'F{index:02d}', 'rtSeconds': feature.getRT(), 'mz': feature.getMZ(),
        'intensity': feature.getIntensity(), 'charge': feature.getCharge(), 'traces': traces,
    }


def format_ts(records):
    def encode(value):
        return json.dumps(value, separators=(', ', ': '), allow_nan=False)

    lines = [
        '// Generated by scripts/extract-lcms-fixture.py from the pinned OpenMS mzML run.',
        "import type { LcMsFeatureData } from './model'",
        '',
        'export const measuredLcMsData: LcMsFeatureData = {',
        '  features: [',
    ]
    for feature in records:
        lines.append('    {')
        feature_fields = {key: value for key, value in feature.items() if key != 'traces'}
        lines.append('      ' + encode(feature_fields)[1:-1] + ',')
        lines.append('      traces: [')
        for trace in feature['traces']:
            trace_fields = {key: value for key, value in trace.items() if key not in ('hull', 'samples')}
            lines.append('        {')
            lines.append('          ' + encode(trace_fields)[1:-1] + ',')
            for field in ('hull', 'samples'):
                lines.append(f'          {field}: [')
                for pair in trace[field]:
                    lines.append('            ' + encode(pair) + ',')
                lines.append('          ],')
            lines.append('        },')
        lines.extend(('      ],', '    },'))
    return '\n'.join(lines + ['  ],', '}', ''])


def main():
    parser = argparse.ArgumentParser(description=__doc__, epilog=f'Measurements: {SOURCE_URL}')
    parser.add_argument('mzml', type=Path, help='Exact pinned Metabolomics_1.mzML file')
    parser.add_argument('output', type=Path, help='Destination measured-features.ts')
    args = parser.parse_args()
    if oms.__version__ != '3.6.0':
        raise ValueError(f'Expected pyOpenMS 3.6.0, got {oms.__version__}')
    if hashlib.sha256(args.mzml.read_bytes()).hexdigest() != SOURCE_SHA256:
        raise ValueError('The mzML input does not match the pinned source run')

    experiment = oms.MSExperiment()
    oms.MzMLFile().load(str(args.mzml), experiment)
    experiment.sortSpectra(True)
    scans = [
        (scan.getNativeID(), scan.getRT(), *scan.get_peaks())
        for scan in experiment if scan.getMSLevel() == 1
    ]
    features = detect_features(experiment)
    records = [make_record(feature, index, scans) for index, feature in enumerate(features, 1)]
    args.output.write_text(format_ts(records))
    default = max(records, key=lambda feature: feature['intensity'])
    print(f"{len(records)} features from {len(scans)} MS1 scans. Highest detector peak area: {default['id']}")


if __name__ == '__main__':
    main()
