#!/usr/bin/env python3
"""Extract the measured startup-overlay fixture from the pinned Zenodo v1.1.3 sensor archives.

Download the Sensors and Sensor_Uncertainties ZIPs from
https://zenodo.org/records/22250958. Run this script with both archive paths
and a destination for fixture.ts. Python 3.11+ standard library only.
"""

from argparse import ArgumentParser
import csv
from hashlib import file_digest
from io import TextIOWrapper
import json
from math import isfinite
from pathlib import Path
from zipfile import ZipFile

ARCHIVES = (
    (
        "01_Batch_Distillation_Plant_M-202210_Timeseries_Sensors",
        "1f53b67401458735f4e12c51e84415a52a04104e150e4cc9d560ab9d39545d01",
    ),
    (
        "03_Batch_Distillation_Plant_M-202210_Timeseries_Sensor_Uncertainties",
        "10052b724868c247dabab6a9b9de9e834742f7b87ee361c1c2b963a4316579f4",
    ),
)
MIXTURE = "batch_dist_ternary_butan-1-ol+propan-2-ol+water"
OP_POINTS = ("001", "002", "003")
COLUMNS = ("T703", "T705")
DAY_SECONDS = 86400
STEP = 30
WINDOW_END = 6000
OPERATION_TAIL = 300
DEADLINE = 2700


def second_of_day(time: str) -> int:
    hour, minute, second = map(int, time.split(":"))
    if not (0 <= hour < 24 and 0 <= minute < 60 and 0 <= second < 60):
        raise ValueError(f"Invalid clock time {time!r}")
    return hour * 3600 + minute * 60 + second


def read_phase(
    sensors: ZipFile, uncertainties: ZipFile, phase: str, run_path: str
) -> list[tuple[int, tuple[float | None, ...]]]:
    recording = f"{phase}/{MIXTURE}/{run_path}"
    with (
        TextIOWrapper(sensors.open(f"{ARCHIVES[0][0]}/{recording}"), encoding="utf-8-sig") as values,
        TextIOWrapper(uncertainties.open(f"{ARCHIVES[1][0]}/{recording}"), encoding="utf-8-sig") as flags,
    ):
        rows = []
        for row, uncertainty in zip(csv.DictReader(values), csv.DictReader(flags), strict=True):
            if row["Time"] != uncertainty["Time"] or uncertainty["Data_interpolated"] not in {"0", "1"}:
                raise ValueError(f"Inconsistent sensor metadata in {recording}")
            if uncertainty["Data_interpolated"] == "1":
                readings = (None,) * len(COLUMNS)
            else:
                readings = tuple(float(row[column]) for column in COLUMNS)
                if not all(map(isfinite, readings)):
                    raise ValueError(f"Non-finite measurement in {recording}")
            rows.append((second_of_day(row["Time"]), readings))
    if not rows:
        raise ValueError(f"Empty {recording}")
    return rows


def extract_run(sensors: ZipFile, uncertainties: ZipFile, run_path: str) -> dict:
    startup = read_phase(sensors, uncertainties, "Startup", run_path)
    operation = read_phase(sensors, uncertainties, "Operation", run_path)

    # Retain each run's clock origin. Modular differences unwrap a midnight crossing.
    origin = startup[0][0]
    elapsed = lambda time: (time - origin) % DAY_SECONDS
    readiness = elapsed(operation[0][0])
    observed_until = elapsed(operation[-1][0])
    if not 0 < readiness <= WINDOW_END or readiness > observed_until:
        raise ValueError(f"Invalid phase positions in {run_path}")

    startup_offsets = [elapsed(time) for time, _ in startup]
    operation_offsets = [elapsed(time) for time, _ in operation]
    if (
        startup_offsets != sorted(startup_offsets)
        or operation_offsets != sorted(operation_offsets)
        or startup_offsets[-1] > readiness
    ):
        raise ValueError(f"Unordered or overlapping clocks in {run_path}")

    # Keep the last row at repeated seconds. The Operation row wins at its boundary.
    readings = {elapsed(time): values for time, values in (*startup, *operation)}
    stop = min(WINDOW_END, readiness + OPERATION_TAIL, observed_until)
    offsets = sorted({*range(0, stop + 1, STEP), readiness, stop})
    rows = [[origin + offset, *readings.get(offset, (None,) * len(COLUMNS))] for offset in offsets]

    operating_point, filename = run_path.split("/")
    point = operating_point.removeprefix("operating_point_")
    experiment = Path(filename).stem.removeprefix("train_normal_experiment_")
    kind = "train"
    if experiment == Path(filename).stem:
        kind = "test"
        experiment = experiment.removeprefix("test_anormal_experiment_")
    if point not in OP_POINTS or not experiment.isdigit():
        raise ValueError(f"Unexpected run ID in {run_path}")
    return {
        "id": f"op{point}-{kind}{experiment}",
        "label": f"OP {point} / {kind} {experiment}",
        "eventTime": origin,
        "readyTime": origin + readiness,
        "observedUntil": origin + observed_until,
        "samples": rows,
    }


def build_fixture(runs: list[dict]) -> str:
    lines = [
        "// Generated by scripts/extract-startup-overlay.py from Zenodo 10.5281/zenodo.22250958.",
        "import type { StartupOverlayData } from './model'",
        "",
        "const records: readonly {",
        "  id: string",
        "  label: string",
        "  eventTime: number",
        "  readyTime: number",
        "  observedUntil: number",
        "  samples: readonly (readonly [time: number, reboiler: number | null, columnTop: number | null])[]",
        "}[] = [",
    ]
    for run in runs:
        samples = run["samples"]
        fields = {key: value for key, value in run.items() if key != "samples"}
        lines.append(f"  {json.dumps(fields, ensure_ascii=False)[:-1]}, \"samples\": [")
        lines.extend(f"    {json.dumps(sample, allow_nan=False)}," for sample in samples)
        lines.append("  ]},")
    lines.extend([
        "]",
        "",
        "export const measuredStartupOverlay: StartupOverlayData = {",
        f"  window: [0, {WINDOW_END}],",
        f"  step: {STEP},",
        f"  deadline: {DEADLINE},",
        "  signals: [",
        f"    {{ id: 'T703', label: 'Reboiler liquid temperature', unit: '°C', maxGap: {STEP} }},",
        f"    {{ id: 'T705', label: 'Column-top fluid temperature', unit: '°C', maxGap: {STEP} }},",
        "  ],",
        "  runs: records.map(({ samples, ...run }) => ({",
        "    ...run,",
        "    traces: {",
        "      T703: samples.map(([time, value]) => ({ time, value })),",
        "      T705: samples.map(([time, , value]) => ({ time, value })),",
        "    },",
        "  })),",
        "}",
        "",
        "export const startupOverlayInitialRun = 'op001-test001'",
        "",
        "export const startupOverlaySource = {",
        "  title: 'Batch Distillation Data for Developing Machine Learning Anomaly Detection Methods',",
        "  url: 'https://zenodo.org/records/22250958',",
        "  license: 'CC BY 4.0',",
        "  licenseUrl: 'https://creativecommons.org/licenses/by/4.0/',",
        "  caption: 'Arweiler et al. (2026), laboratory batch distillation, operating points 001–003 for 1-butanol, 2-propanol and water. Time zero is the first archived startup timestamp. Readiness is the first archived operation timestamp. Traces retain 30-second readings and the phase boundary, with up to five minutes of operation shown. Missing samples and rows flagged as interpolated by the authors are omitted from the trace. The 45-minute deadline is an illustrative comparison.',",
        "}",
        "",
    ])
    return "\n".join(lines)


def main() -> None:
    parser = ArgumentParser(description=__doc__)
    parser.add_argument("sensors", type=Path)
    parser.add_argument("uncertainties", type=Path)
    parser.add_argument("output", type=Path)
    args = parser.parse_args()
    for path, (_, expected) in zip((args.sensors, args.uncertainties), ARCHIVES, strict=True):
        with path.open("rb") as source:
            if file_digest(source, "sha256").hexdigest() != expected:
                parser.error(f"{path} does not match the pinned v1.1.3 archive")

    with ZipFile(args.sensors) as sensors, ZipFile(args.uncertainties) as uncertainties:
        run_paths = []
        for operating_point in OP_POINTS:
            prefix = f"{ARCHIVES[0][0]}/Startup/{MIXTURE}/"
            point_path = f"{prefix}operating_point_{operating_point}/"
            run_paths.extend(name.removeprefix(prefix) for name in sensors.namelist()
                             if name.startswith(point_path) and name.endswith(".csv"))
        runs = [extract_run(sensors, uncertainties, name) for name in sorted(run_paths)]
    if len(runs) != 30:
        raise ValueError("Expected all 30 runs from operating points 001–003")
    args.output.write_text(build_fixture(runs), encoding="utf-8")


if __name__ == "__main__":
    main()
