#!/usr/bin/env python3
"""Generate October 2008 holdout classifier scores from the UCI SECOM archive.

Source: McCann and Johnston (2008), https://doi.org/10.24432/C54305 (CC BY 4.0).
Archive: https://archive.ics.uci.edu/static/public/179/secom.zip
Tested with Python 3.14, NumPy 2.4.4, SciPy 1.18.1 and scikit-learn 1.8.0.
"""

import argparse
import hashlib
from datetime import datetime
from io import BytesIO
from pathlib import Path
from zipfile import ZipFile

import numpy as np
from sklearn.feature_selection import VarianceThreshold
from sklearn.impute import SimpleImputer
from sklearn.linear_model import LogisticRegression
from sklearn.pipeline import make_pipeline
from sklearn.preprocessing import StandardScaler
from threadpoolctl import threadpool_limits


ARCHIVE_SHA256 = 'eea568baf3c2229096d7d294cf0b096b5502bd96d92c0b80a65b84714059be8e'
HOLDOUT_START = datetime(2008, 10, 1)
ILLUSTRATIVE_THRESHOLD = 0.25


def read_source(path):
    content = path.read_bytes()
    if hashlib.sha256(content).hexdigest() != ARCHIVE_SHA256:
        raise ValueError('Expected the original UCI SECOM archive with the documented SHA-256')
    with ZipFile(BytesIO(content)) as archive:
        measurements = np.loadtxt(BytesIO(archive.read('secom.data')))
        label_rows = archive.read('secom_labels.data').decode('ascii').splitlines()

    parsed_labels = [row.split(maxsplit=1) for row in label_rows]
    y = np.array([int(label) for label, _ in parsed_labels])
    timestamps = [datetime.strptime(stamp.strip('"'), '%d/%m/%Y %H:%M:%S') for _, stamp in parsed_labels]
    if measurements.shape != (1567, 590) or len(y) != len(measurements) or set(y) != {-1, 1}:
        raise ValueError('The measurement and label files do not match the published dataset')
    return measurements, y == 1, timestamps


def fit_holdout_scores(source):
    x, y, timestamps = read_source(source)
    train = np.array([stamp < HOLDOUT_START for stamp in timestamps])
    train_x, train_y = x[train], y[train]
    test_x, test_y = x[~train], y[~train]
    if (len(train_y), int(train_y.sum()), len(test_y), int(test_y.sum())) != (1208, 82, 359, 22):
        raise ValueError('Unexpected counts in the timestamp partition')

    model = make_pipeline(
        SimpleImputer(strategy='median', keep_empty_features=True),
        VarianceThreshold(),
        StandardScaler(),
        LogisticRegression(
            C=0.01, class_weight='balanced', max_iter=2000, solver='lbfgs', tol=1e-8,
        ),
    )
    # Empty training columns are imputed to zero and then discarded along with
    # other constant columns. All preprocessing is fitted on the training rows.
    with threadpool_limits(limits=1):
        model.fit(train_x, train_y)
        scores = model.predict_proba(test_x)[:, 1]
    ids = np.flatnonzero(~train) + 1
    return zip(ids, scores, test_y, strict=True)


def render_fixture(scores):
    header = """// Generated by scripts/extract-secom-classifier.py from the UCI SECOM archive.
// Adapted from McCann and Johnston (2008), CC BY 4.0. See THIRD_PARTY_NOTICES.md.
import type { ClassifierThresholdData } from './model'

const holdoutScores: readonly (readonly [row: number, score: number, failed: 0 | 1])[] = ["""
    footer = f"""]

export const secomClassifierData: ClassifierThresholdData = {{
  positiveLabel: 'Failed line test',
  negativeLabel: 'Passed line test',
  predictions: holdoutScores.map(([row, score, failed]) => ({{
    id: `SECOM ${{row}}`,
    score,
    actual: failed === 1,
  }})),
}}

export const secomInitialThreshold = {ILLUSTRATIVE_THRESHOLD}

export const secomClassifierSource = {{
  title: 'SECOM semiconductor manufacturing data',
  authors: 'Michael McCann and Adrian Johnston',
  year: 2008,
  doi: '10.24432/C54305',
  url: 'https://doi.org/10.24432/C54305',
  license: 'CC BY 4.0',
  licenseUrl: 'https://creativecommons.org/licenses/by/4.0/',
  trainingCount: 1208,
  trainingFailures: 82,
  holdoutCount: 359,
  holdoutFailures: 22,
  holdoutStart: '2008-10-01',
  holdoutEnd: '2008-10-17',
  caption:
    'October 2008 holdout of 359 production entities (22 failed line tests). Class-balanced logistic regression fitted to 1,208 July–September entities. The scores are uncalibrated.',
}} as const
"""
    rows = [f'  [{row}, {score:.8f}, {int(failed)}],' for row, score, failed in scores]
    return '\n'.join([header, *rows, footer])


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('archive', type=Path, help='Original UCI secom.zip file')
    parser.add_argument('output', type=Path, help='Destination fixture.ts')
    args = parser.parse_args()
    args.output.write_text(render_fixture(fit_holdout_scores(args.archive)), encoding='utf-8')


if __name__ == '__main__':
    main()
