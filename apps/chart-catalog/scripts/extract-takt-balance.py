#!/usr/bin/env python3
"""Regenerate the takt fixture from the versioned Zenodo workbook using Python 3.

Download the XLSX at https://zenodo.org/records/22734493. Run this script with
that file and redirect stdout to src/charts/scientific/takt-balance/fixture.ts.
"""

import argparse
from decimal import Decimal
from hashlib import sha256
import json
from pathlib import Path
import xml.etree.ElementTree as ET
from zipfile import ZipFile

WORKBOOK_SHA256 = "9552c9f0f981400e0e01bb32be83af5333b1bd9b2fbe700787b421caa1f98a3d"
NAMESPACE = {"m": "http://schemas.openxmlformats.org/spreadsheetml/2006/main"}
STATIONS = (("operator-1", "Operator 1"), ("operator-2", "Operator 2"), ("operator-3", "Operator 3"))
PARCELS = (
    ("processes-1-4", "Processes 1–4", "P1–4", 4, 7, True),
    ("processes-5-8", "Processes 5–8", "P5–8", 8, 11, True),
    ("processes-9-12", "Processes 9–12", "P9–12", 12, 15, True),
    ("process-13", "Process 13", "P13", 16, 16, True),
    ("support", "Irregular work and materials", "Support", 17, 19, False),
    ("walking", "Walking", "Walk", 20, 20, False),
)
CAPTION = (
    "Normalized pre-automation work-element times from an automotive line. "
    "The stacks sum the published element cells. Operator 3's cells add to 11.2 s "
    "and the workbook's total cell reads 11.4 s. The 10.5 s takt and relocation "
    "rules are scenario assumptions. The comparison holds durations constant when a parcel moves."
)


def work_elements(workbook):
    if sha256(workbook.read_bytes()).hexdigest() != WORKBOOK_SHA256:
        raise ValueError("The workbook does not match the pinned Zenodo v1 file.")
    with ZipFile(workbook) as archive:
        yamazumi = ET.fromstring(archive.read("xl/worksheets/sheet4.xml"))

    # Stored XML decimals can expose binary floating point artifacts such as
    # 1.1000000000000001. The source workbook reports work elements to 0.1 s.
    return {
        cell.attrib["r"]: Decimal(cell.findtext("m:v", namespaces=NAMESPACE)).quantize(Decimal("0.1"))
        for cell in yamazumi.findall(".//m:sheetData/m:row/m:c", NAMESPACE)
        if cell.get("t", "n") == "n" and cell.find("m:v", NAMESPACE) is not None
    }


def tasks_from_sheet(cells):
    for column, (station, operator) in zip("DEF", STATIONS, strict=True):
        for key, label, short_label, row_start, row_end, movable in PARCELS:
            seconds = sum(cells.get(f"{column}{row}", Decimal(0)) for row in range(row_start, row_end + 1))
            if seconds == 0:
                continue
            task = {
                "id": f"{station}-{key}",
                "label": label if key == "process-13" else f"{label} · source {operator.lower()}",
                "shortLabel": short_label,
                "seconds": float(seconds),
                "stationId": station,
            }
            if not movable:
                task["allowedStations"] = [station]
            yield task


def write_fixture(cells):
    print('''import type { TaktBalanceData } from './model'

// Generated by scripts/extract-takt-balance.py from the pinned CC BY 4.0 workbook.
export const measuredTaktBalance: TaktBalanceData = {
  availableSeconds: 37800,
  demand: 3600,
  stations: [''')
    for station, label in STATIONS:
        print(f"    {json.dumps({'id': station, 'label': label}, ensure_ascii=False)},")
    print("  ],")
    print("  tasks: [")
    for task in tasks_from_sheet(cells):
        print(f"    {json.dumps(task, ensure_ascii=False)},")
    print('''  ],
}

export const taktBalanceInitialTask = 'operator-3-process-13'

export const taktBalanceSource = {''')
    properties = {
        "title": "Automotive manufacturing Yamazumi work elements",
        "url": "https://doi.org/10.5281/zenodo.22734493",
        "license": "CC BY 4.0",
        "licenseUrl": "https://creativecommons.org/licenses/by/4.0/",
        "caption": CAPTION,
    }
    for key, value in properties.items():
        print(f"  {key}: {json.dumps(value, ensure_ascii=False)},")
    print("}")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("workbook", type=Path)
    args = parser.parse_args()
    write_fixture(work_elements(args.workbook))
