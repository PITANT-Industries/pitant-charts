#!/usr/bin/env python3
"""Generate the energy operating map fixture from the pinned Kim et al. CSVs.

Download the two original files from imi_vm20i/dataset10 in Kaggle version 2:
https://www.kaggle.com/datasets/manufuturetoday/multi-sensor-for-metal-milling-anomaly/versions/2

Run with the label CSV followed by the MTConnect CSV, redirecting stdout to
apps/chart-catalog/src/charts/scientific/energy-operating-map/fixture.ts.
"""

import argparse
from bisect import bisect_left, bisect_right
from collections import Counter
import csv
from decimal import Decimal
from hashlib import sha256
import json
from pathlib import Path

LABEL_SHA = "a560a5bb2a98b15d02ef4b0fd9cd5b5404501caf50decb91d1411bca489a3125"
METER_SHA = "2ab3dedf50aa0545f51f040518cfbdcc973bd06625d98d3bf16b973da471bc8d"
SPEEDS = (8500, 9500, 10500, 11500)
DEPTHS = (Decimal("0.1016"), Decimal("0.508"))
DIRECTIONS = {"UP", "DOWN"}
MAX_GAP = Decimal("0.25")
CAPTION = (
    "Sixteen normal AA 6061 milling passes with Tool B at 63.5 mm/s programmed feed and "
    "26.67 mm radial depth. Each setting combines one up-milling and one down-milling pass. "
    "The integral uses logged main-supply watts inside the annotated cut, including the machine's "
    "baseline draw during that window. Energy is reported per cutting pass. One pass has an "
    "uncovered interval. Its trace is shown, and its energy is omitted from the setting median."
)


def rows(path, expected_sha):
    if sha256(path.read_bytes()).hexdigest() != expected_sha:
        raise ValueError(f"{path.name} does not match the pinned Kaggle v2 source file.")
    with path.open(encoding="utf-8-sig", newline="") as source:
        return list(csv.DictReader(source))


def extract(labels_path, meter_path):
    labels = rows(labels_path, LABEL_SHA)
    meter = rows(meter_path, METER_SHA)
    times = [Decimal(row["time"]) for row in meter]
    if not times or any(not time.is_finite() for time in times) or any(
        second <= first for first, second in zip(times, times[1:])
    ):
        raise ValueError("Expected finite, strictly increasing MTConnect sample times.")

    setting_counts = Counter()
    partial = []
    cuts = []
    for number, label in enumerate(labels, start=1):
        if Decimal(label["F"]) != Decimal("63.5"):
            continue
        speed = int(label["N"])
        depth = Decimal(label["ap"])
        direction = label["direction"]
        start = Decimal(label["start"])
        end = Decimal(label["end"])
        if (
            (label["label"], label["Tool"], label["Workpiece"], label["Z"], label["D"], label["ae"])
            != ("0", "B", "AA 6061", "3", "50.8", "26.67")
            or speed not in SPEEDS
            or depth not in DEPTHS
            or direction not in DIRECTIONS
            or not times[0] <= start < end <= times[-1]
        ):
            raise ValueError(f"Source row {number} is outside the fixed-feed Tool B cohort.")
        setting_counts[speed, depth, direction] += 1

        lo = bisect_right(times, start) - 1
        hi = bisect_left(times, end)
        readings = []
        for row, time in zip(meter[lo : hi + 1], times[lo : hi + 1], strict=True):
            watts = Decimal(row["watt"])
            if not watts.is_finite() or watts < 0 or Decimal(row["Spindle_Speed"]) != speed:
                raise ValueError(f"Unexpected power or speed reading for source row {number}.")
            readings.append([float(time), float(watts)])
        if any(
            second - first > MAX_GAP and max(first, start) < min(second, end)
            for first, second in zip(times[lo:hi], times[lo + 1 : hi + 1])
        ):
            partial.append(number)
        cuts.append([number, direction.title(), speed, float(depth), float(start), float(end), readings])

    expected = Counter((speed, depth, direction) for speed in SPEEDS for depth in DEPTHS for direction in DIRECTIONS)
    if setting_counts != expected or partial != [52]:
        raise ValueError("Expected paired up and down passes at eight settings and one incomplete cut.")
    return cuts


def emit(cuts):
    print("// Generated by scripts/extract-energy-operating-map.py from the pinned Kim et al. source.")
    print("import type { EnergyOperatingMapData } from './model'\n")
    print("const cuts = [")
    for cut in cuts:
        metadata = ", ".join(json.dumps(value) for value in cut[:-1])
        print(f"  [{metadata}, [")
        for reading in cut[-1]:
            print(f"    {json.dumps(reading)},")
        print("  ]],")
    print("] as const\n")
    print("export const measuredEnergyOperatingMap: EnergyOperatingMapData = {")
    print("  unit: 'cut',")
    print("  speed: { label: 'Spindle speed', unit: 'rpm' },")
    print("  load: { label: 'Axial depth of cut', unit: 'mm' },")
    print("  runs: cuts.map(([number, direction, speed, load, start, end, samples]) => ({")
    print("    id: `pass-${number}`,")
    print("    label: `Pass ${number} · ${direction.toLowerCase()} milling`,")
    print(f"    speed, load, start, end, units: 1, maxGap: {MAX_GAP},")
    print("    readings: samples.map(([time, watts]) => ({ time, watts })),")
    print("  })),")
    print("}\n")
    print("export const energyOperatingInitialRun = 'pass-20'\n")
    print("export const energyOperatingSource = {")
    print("  title: 'Kim et al. Multi-Sensor and MTConnect milling dataset, v2',")
    print("  url: 'https://doi.org/10.34740/kaggle/ds/8392825',")
    print("  license: 'CC BY 4.0',")
    print("  licenseUrl: 'https://creativecommons.org/licenses/by/4.0/',")
    print(f"  caption: {json.dumps(CAPTION)},")
    print("}")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("labels", type=Path)
    parser.add_argument("meter", type=Path)
    args = parser.parse_args()
    emit(extract(args.labels, args.meter))
