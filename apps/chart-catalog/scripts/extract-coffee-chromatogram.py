#!/usr/bin/env python3
"""Extract the measured coffee trace with SciPy 1.17.0.

Source: Erny, Moeenfard, and Alves (2021), https://doi.org/10.5281/zenodo.5412345.
Download LCDAD_Coffee_KOKPCOCP.mat from the record before running this script.
"""

import argparse
import hashlib
import json
from pathlib import Path

from scipy.io import loadmat


SOURCE_SHA256 = 'b93a353f5f522607a0c229873e82e32825eba1dca3ab9e562be5482ab405bfee'
WAVELENGTH_NM = 225
COFFEE_INJECTION = 0
START_MINUTES = 12
END_MINUTES = 22


def extract(source):
    if hashlib.sha256(source.read_bytes()).hexdigest() != SOURCE_SHA256:
        raise ValueError('Expected the published LCDAD_Coffee_KOKPCOCP.mat file')

    data = loadmat(source, simplify_cells=True, variable_names=['Data'])['Data']
    wavelength_index = data['Wavelength'].tolist().index(WAVELENGTH_NM)
    retention = data['Time']
    response = data['Data_samples'][:, wavelength_index, COFFEE_INJECTION]
    return [
        (float(time), int(signal))
        for time, signal in zip(retention, response, strict=True)
        if START_MINUTES <= time <= END_MINUTES
    ]


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('source', type=Path, help='Original Zenodo .mat file')
    parser.add_argument('output', type=Path, help='Destination measured-samples.ts')
    args = parser.parse_args()
    samples = extract(args.source)
    lines = [
        '// Generated by scripts/extract-coffee-chromatogram.py from Zenodo record 5412345.',
        '// The measurements are licensed under CC BY 4.0. See THIRD_PARTY_NOTICES.md.',
        "import type { ChromatogramData } from './model'",
        '',
        'export const measuredSamples: ChromatogramData[\'samples\'] = [',
        *(f'  {json.dumps(sample, allow_nan=False)},' for sample in samples),
        ']',
        '',
    ]
    args.output.write_text('\n'.join(lines), encoding='utf-8')


if __name__ == '__main__':
    main()
