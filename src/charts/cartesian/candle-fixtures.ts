function datedRows(start: Date, samples: readonly Candle[], days = 1): CartesianData {
  const hour = 60 * 60 * 1000;
  const endOfSummerTime = Date.UTC(2026, 9, 26);
  const dates = samples.map((_, index) => {
    const day = +start + index * days * 24 * hour;
    // The reference records Berlin midnight, so the October clock change adds one hour.
    return new Date(day - (day < endOfSummerTime ? 2 : 1) * hour);
  });
  return {
    categories: dates.map(date => candleDateLabel.format(date)),
    candleDates: dates,
    series: [],
    rows: samples.map(([open, close, low, high]) => ({ open, close, low, high })),
  };
}

export function candleFixture(id: string): CartesianData {
  switch (id) {
    case "candlestick-minimal": return datedRows(new Date(Date.UTC(2026, 8, 1)), minimal);
    case "candlestick-colors": return datedRows(new Date(Date.UTC(2026, 6, 6)), colors, 7);
    case "candlestick-range": return datedRows(new Date(Date.UTC(2026, 7, 1)), range);
    case "candlestick-crosshair": return datedRows(new Date(Date.UTC(2026, 9, 2)), range.slice(-30));
    case "candlestick-pattern": return datedRows(new Date(Date.UTC(2026, 9, 8)), range.slice(-24));
    default: return datedRows(new Date(Date.UTC(2026, 9, 1)), daily);
  }
}
